begin;

create table if not exists public.profiles (
  id bigint primary key,
  username text,
  first_name text,
  photo_url text,
  coins integer not null default 0,
  total_wins integer not null default 0,
  games_played integer not null default 0,
  created_at timestamptz not null default now()
);

update public.profiles set coins = 0 where coins is null;
update public.profiles set total_wins = 0 where total_wins is null;
update public.profiles set games_played = 0 where games_played is null;

alter table public.profiles alter column coins set default 0;
alter table public.profiles alter column coins set not null;
alter table public.profiles alter column total_wins set not null;
alter table public.profiles alter column games_played set not null;
alter table public.profiles add column if not exists daily_claimed_on date;
alter table public.profiles add column if not exists subscription_reward_claimed boolean not null default false;
update public.profiles set subscription_reward_claimed = false where subscription_reward_claimed is null;
alter table public.profiles alter column subscription_reward_claimed set default false;
alter table public.profiles alter column subscription_reward_claimed set not null;
alter table public.profiles enable row level security;

grant usage on schema public to anon, authenticated;
grant select, insert, update on public.profiles to anon, authenticated;

drop policy if exists "Public profiles are viewable by everyone." on public.profiles;
drop policy if exists "Users can insert their own profile." on public.profiles;
drop policy if exists "Users can update own profile." on public.profiles;
drop policy if exists "Players can read their own profile" on public.profiles;
drop policy if exists "Players can create their own profile" on public.profiles;

create policy "Public profiles are viewable by everyone."
  on public.profiles for select
  to anon, authenticated
  using (true);

create policy "Users can insert their own profile."
  on public.profiles for insert
  to anon, authenticated
  with check (true);

create policy "Users can update own profile."
  on public.profiles for update
  to anon, authenticated
  using (true)
  with check (true);

create index if not exists profiles_leaderboard_idx
  on public.profiles (total_wins desc, coins desc);

create table if not exists public.quiz_activity (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.profiles (id) on delete cascade,
  score integer not null check (score between 0 and 10),
  played_at timestamptz not null default now()
);

alter table public.quiz_activity enable row level security;
grant select on public.quiz_activity to anon, authenticated;

drop policy if exists "Quiz activity is publicly readable" on public.quiz_activity;
create policy "Quiz activity is publicly readable"
  on public.quiz_activity for select
  to anon, authenticated
  using (true);

create index if not exists quiz_activity_player_date_idx
  on public.quiz_activity (player_id, played_at desc);

create or replace function public.record_quiz_result(p_player_id bigint, p_score integer)
returns setof public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  correct_answers integer := greatest(0, least(coalesce(p_score, 0), 10));
  updated_profile public.profiles;
begin
  update public.profiles
  set coins = coins + correct_answers * 100,
      total_wins = total_wins + correct_answers,
      games_played = games_played + 1
  where id = p_player_id
  returning * into updated_profile;

  if not found then
    raise exception 'Profile % does not exist', p_player_id;
  end if;

  insert into public.quiz_activity (player_id, score)
  values (p_player_id, correct_answers);

  return next updated_profile;
  return;
end;
$$;

revoke all on function public.record_quiz_result(bigint, integer) from public;
grant execute on function public.record_quiz_result(bigint, integer) to anon, authenticated;

create or replace function public.spend_quiz_hint(p_player_id bigint)
returns table (new_coins integer, spent boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_coins integer;
begin
  update public.profiles as p
  set coins = p.coins - 150
  where p.id = p_player_id
    and p.coins >= 150
  returning p.coins into updated_coins;

  if found then
    return query select updated_coins, true;
    return;
  end if;

  return query
    select p.coins, false
    from public.profiles as p
    where p.id = p_player_id;
end;
$$;

revoke all on function public.spend_quiz_hint(bigint) from public;
revoke all on function public.spend_quiz_hint(bigint) from anon, authenticated;
grant execute on function public.spend_quiz_hint(bigint) to service_role;

create or replace function public.claim_daily_reward(p_player_id bigint)
returns table (new_coins integer, claim_date date, claimed boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  utc_today date := (now() at time zone 'UTC')::date;
  updated_coins integer;
  updated_claim_date date;
begin
  update public.profiles as p
  set coins = p.coins + 50,
      daily_claimed_on = utc_today
  where p.id = p_player_id
    and (p.daily_claimed_on is null or p.daily_claimed_on < utc_today)
  returning p.coins, p.daily_claimed_on into updated_coins, updated_claim_date;

  if found then
    return query select updated_coins, updated_claim_date, true;
    return;
  end if;

  return query
    select p.coins, p.daily_claimed_on, false
    from public.profiles as p
    where p.id = p_player_id;
end;
$$;

revoke all on function public.claim_daily_reward(bigint) from public, anon, authenticated;
grant execute on function public.claim_daily_reward(bigint) to service_role;

create or replace function public.claim_subscription_reward(p_player_id bigint)
returns table (new_coins integer, claimed boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_coins integer;
begin
  update public.profiles as p
  set coins = p.coins + 100,
      subscription_reward_claimed = true
  where p.id = p_player_id
    and p.subscription_reward_claimed = false
  returning p.coins into updated_coins;

  if found then
    return query select updated_coins, true;
    return;
  end if;

  return query
    select p.coins, false
    from public.profiles as p
    where p.id = p_player_id;
end;
$$;

revoke all on function public.claim_subscription_reward(bigint) from public, anon, authenticated;
grant execute on function public.claim_subscription_reward(bigint) to service_role;

commit;